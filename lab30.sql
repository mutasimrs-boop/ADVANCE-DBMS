SET SERVEROUTPUT ON;

DECLARE
    A NUMBER := 100;
    B NUMBER := 0;
    C NUMBER;

BEGIN
    C := A / B;

    DBMS_OUTPUT.PUT_LINE('Answer = ' || C);

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('SQLCODE = ' || SQLCODE);
        DBMS_OUTPUT.PUT_LINE('SQLERRM = ' || SQLERRM);
END;
/